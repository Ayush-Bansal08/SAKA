/**
 * Builds the SAKA marks from straight lines only: no font, no curves, no raster.
 *
 *   node docs/ui-revamp/brand/generate-logo.mjs
 *
 * Coordinates: cap height 100, baseline y = 100. Every letter is a polygon, then the whole mark is
 * sheared forward. Terminals are cut on the diagonal, which is what makes it read as sharp.
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const OUT = resolve(ROOT, 'apps/web/public/brand');
const n = (v) => Number(v.toFixed(2));

const SLANT = 0.2;
const shear = ([x, y]) => [x + (100 - y) * SLANT, y];
const path = (pts, { dx = 0, dy = 0, s = 1, slant = true } = {}) =>
  `M${pts
    .map((p) => (slant ? shear(p) : p))
    .map(([x, y]) => `${n(x * s + dx)} ${n(y * s + dy)}`)
    .join('L')}Z`;

/** S: one continuous blade with diagonal cuts at both ends. `t` is the stroke weight. */
const glyphS = (t = 14) => {
  const mid = 50;
  const c = 9; // chamfer
  const top = mid - t / 2;
  const bot = mid + t / 2;
  return [
    [84, 0],
    [84 - t, t],
    [t + 3, t],
    [t, t + 3],
    [t, top - 3],
    [t + 3, top],
    [76 - c, top],
    [76, top + c],
    [76, 100 - c],
    [76 - c, 100],
    [-8, 100],
    [-8 + t, 100 - t],
    [76 - t - 3, 100 - t],
    [76 - t, 100 - t - 3],
    [76 - t, bot + 3],
    [76 - t - 3, bot],
    [c, bot],
    [0, bot - c],
    [0, c],
    [c, 0],
  ];
};

/** Λ: no crossbar, a knife-point apex. */
const glyphA = (x, t = 16) => [
  [x + 38, 0],
  [x + 52, 0],
  [x + 92, 100],
  [x + 92 - t, 100],
  [x + 45, 23],
  [x + t, 100],
  [x, 100],
];

/** K: stem, then an arm that spears past the cap height. */
const glyphK = (x, t = 14) => [
  [
    [x, 0],
    [x + t, 0],
    [x + t, 100],
    [x, 100],
  ],
  [
    [x + t, 45],
    [x + 72, -18],
    [x + 73, 2],
    [x + 31, 47],
    [x + 80, 100],
    [x + 62, 100],
    [x + t, 56],
  ],
];

const svg = (viewBox, d, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${title}"><title>${title}</title><path fill="currentColor" d="${d}"/></svg>\n`;

// --- Wordmark ---------------------------------------------------------------------------------
const wordmark =
  path(glyphS()) +
  path(glyphA(106)) +
  glyphK(214)
    .map((p) => path(p))
    .join('') +
  path(glyphA(298));
const WORD_BOX = '-10 -20 432 124';

// --- Symbol (64 grid): the wordmark's S at a heavier weight, so it holds at 16px. ---------------
const symbol = path(glyphS(22), { s: 0.52, dx: 3, dy: 6 });

mkdirSync(OUT, { recursive: true });
for (const stale of ['1', '2', '3'])
  rmSync(resolve(OUT, `saka-symbol-option-${stale}.svg`), { force: true });
rmSync(resolve(OUT, 'saka-symbol-gem.svg'), { force: true });
const write = (name, body) => writeFileSync(resolve(OUT, name), body);
write('saka-wordmark.svg', svg(WORD_BOX, wordmark, 'SAKA'));
write('saka-symbol.svg', svg('0 0 64 64', symbol, 'SAKA'));

writeFileSync(
  resolve(ROOT, 'apps/web/public/favicon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><title>SAKA</title><rect width="64" height="64" rx="14" fill="#120c20"/><g transform="translate(6.4 6.4) scale(.8)"><path fill="#c4a8ff" d="${symbol}"/></g></svg>\n`,
);

// The same paths for the app, so the React logo and the files cannot drift apart.
writeFileSync(
  resolve(ROOT, 'apps/web/src/layout/logo-paths.ts'),
  `/** Generated by docs/ui-revamp/brand/generate-logo.mjs. Do not edit by hand. */
export const WORDMARK_VIEWBOX = '${WORD_BOX}';
export const WORDMARK_PATH =
  '${wordmark}';
export const SYMBOL_PATH =
  '${symbol}';
`,
);
console.log('wrote', OUT);
